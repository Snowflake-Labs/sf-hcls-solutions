-- =============================================================================
-- PIPES: High-Performance Snowpipe Streaming (Clinical)
-- =============================================================================

CREATE OR REPLACE PIPE ECG_STREAMING_PIPE
AS
COPY INTO ECG_DATA (DATA, PATIENT_ID, TIMESTAMP_VAL, APP_INGESTION_TIMESTAMP)
FROM (
    SELECT $1, $1:patient_id, $1:timestamp, $1:app_ingestion_timestamp::TIMESTAMP_NTZ
    FROM TABLE(DATA_SOURCE(TYPE => 'STREAMING'))
);

