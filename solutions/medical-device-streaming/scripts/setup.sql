-- =============================================================================
-- VIEW: Consolidated Patient Vital Signs (ASOF Joins)
-- Real-time 5-minute window combining ECG, EDA, and PPG measurements
-- =============================================================================

CREATE OR REPLACE VIEW PATIENT_VITAL_SIGNS AS
WITH patient_list AS (
    SELECT DISTINCT PATIENT_ID
    FROM (
        SELECT PATIENT_ID FROM ECG_DATA_FLATTENED
        UNION ALL
        SELECT PATIENT_ID FROM EDA_DATA_FLATTENED
        UNION ALL
        SELECT PATIENT_ID FROM PPG_DATA_FLATTENED
    )
    WHERE PATIENT_ID IS NOT NULL
),
time_sequence AS (
    SELECT
        DATEADD(
            'SECOND',
            -ROW_NUMBER() OVER (ORDER BY SEQ4()) + 1,
            CONVERT_TIMEZONE('UTC', CURRENT_TIMESTAMP())::TIMESTAMP_NTZ
        ) AS TIMESTAMP_SEC
    FROM TABLE(GENERATOR(ROWCOUNT => 300))
),
time_spine AS (
    SELECT
        p.PATIENT_ID,
        t.TIMESTAMP_SEC
    FROM patient_list AS p
    CROSS JOIN time_sequence AS t
)
SELECT
    spine.PATIENT_ID,
    spine.TIMESTAMP_SEC,

    -- ECG vital signs
    COALESCE(ecg_exact.HEART_RATE, ecg_prop.HEART_RATE) AS ECG_HEART_RATE,
    COALESCE(ecg_exact.RHYTHM_CLASSIFICATION, ecg_prop.RHYTHM_CLASSIFICATION) AS RHYTHM_CLASSIFICATION,
    COALESCE(ecg_exact.QT_INTERVAL, ecg_prop.QT_INTERVAL) AS QT_INTERVAL,
    COALESCE(ecg_exact.ST_ELEVATION, ecg_prop.ST_ELEVATION) AS ST_ELEVATION,
    COALESCE(ecg_exact.SIGNAL_QUALITY, ecg_prop.SIGNAL_QUALITY) AS ECG_SIGNAL_QUALITY,
    COALESCE(ecg_exact.ARTIFACTS_DETECTED, ecg_prop.ARTIFACTS_DETECTED) AS ECG_ARTIFACTS,
    COALESCE(ecg_exact.DEVICE_ID, ecg_prop.DEVICE_ID) AS ECG_DEVICE_ID,
    COALESCE(ecg_exact.SESSION_ID, ecg_prop.SESSION_ID) AS ECG_SESSION_ID,

    -- EDA vital signs
    COALESCE(eda_exact.STRESS_LEVEL, eda_prop.STRESS_LEVEL) AS STRESS_LEVEL,
    COALESCE(eda_exact.AROUSAL_LEVEL, eda_prop.AROUSAL_LEVEL) AS AROUSAL_LEVEL,
    COALESCE(eda_exact.SKIN_CONDUCTANCE_LEVEL, eda_prop.SKIN_CONDUCTANCE_LEVEL) AS SKIN_CONDUCTANCE_LEVEL,
    COALESCE(eda_exact.SKIN_CONDUCTANCE_RESPONSE, eda_prop.SKIN_CONDUCTANCE_RESPONSE) AS SKIN_CONDUCTANCE_RESPONSE,
    COALESCE(eda_exact.EMOTIONAL_VALENCE, eda_prop.EMOTIONAL_VALENCE) AS EMOTIONAL_VALENCE,
    COALESCE(eda_exact.SIGNAL_QUALITY, eda_prop.SIGNAL_QUALITY) AS EDA_SIGNAL_QUALITY,
    COALESCE(eda_exact.DEVICE_ID, eda_prop.DEVICE_ID) AS EDA_DEVICE_ID,
    COALESCE(eda_exact.SESSION_ID, eda_prop.SESSION_ID) AS EDA_SESSION_ID,

    -- PPG vital signs
    COALESCE(ppg_exact.SPO2, ppg_prop.SPO2) AS SPO2,
    COALESCE(ppg_exact.HEART_RATE, ppg_prop.HEART_RATE) AS PPG_HEART_RATE,
    COALESCE(ppg_exact.SYSTOLIC_BP, ppg_prop.SYSTOLIC_BP) AS SYSTOLIC_BP,
    COALESCE(ppg_exact.DIASTOLIC_BP, ppg_prop.DIASTOLIC_BP) AS DIASTOLIC_BP,
    COALESCE(ppg_exact.PULSE_WAVE_VELOCITY, ppg_prop.PULSE_WAVE_VELOCITY) AS PULSE_WAVE_VELOCITY,
    COALESCE(ppg_exact.ARTERIAL_STIFFNESS, ppg_prop.ARTERIAL_STIFFNESS) AS ARTERIAL_STIFFNESS,
    COALESCE(ppg_exact.PERFUSION_INDEX, ppg_prop.PERFUSION_INDEX) AS PERFUSION_INDEX,
    COALESCE(ppg_exact.SIGNAL_QUALITY, ppg_prop.SIGNAL_QUALITY) AS PPG_SIGNAL_QUALITY,
    COALESCE(ppg_exact.MOTION_ARTIFACTS, ppg_prop.MOTION_ARTIFACTS) AS PPG_MOTION_ARTIFACTS,
    COALESCE(ppg_exact.DEVICE_ID, ppg_prop.DEVICE_ID) AS PPG_DEVICE_ID,
    COALESCE(ppg_exact.SESSION_ID, ppg_prop.SESSION_ID) AS PPG_SESSION_ID,

    -- Source timestamps
    COALESCE(ecg_exact.TIMESTAMP_VAL, ecg_prop.TIMESTAMP_VAL) AS ECG_SOURCE_TIMESTAMP,
    COALESCE(eda_exact.TIMESTAMP_VAL, eda_prop.TIMESTAMP_VAL) AS EDA_SOURCE_TIMESTAMP,
    COALESCE(ppg_exact.TIMESTAMP_VAL, ppg_prop.TIMESTAMP_VAL) AS PPG_SOURCE_TIMESTAMP,

    -- Data freshness (seconds since actual reading)
    CASE
        WHEN ecg_exact.TIMESTAMP_VAL IS NOT NULL THEN 0
        WHEN ecg_prop.TIMESTAMP_VAL IS NOT NULL THEN
            TIMESTAMPDIFF('SECOND', ecg_prop.TIMESTAMP_VAL, spine.TIMESTAMP_SEC)
        ELSE NULL
    END AS ECG_AGE_SECONDS,
    CASE
        WHEN eda_exact.TIMESTAMP_VAL IS NOT NULL THEN 0
        WHEN eda_prop.TIMESTAMP_VAL IS NOT NULL THEN
            TIMESTAMPDIFF('SECOND', eda_prop.TIMESTAMP_VAL, spine.TIMESTAMP_SEC)
        ELSE NULL
    END AS EDA_AGE_SECONDS,
    CASE
        WHEN ppg_exact.TIMESTAMP_VAL IS NOT NULL THEN 0
        WHEN ppg_prop.TIMESTAMP_VAL IS NOT NULL THEN
            TIMESTAMPDIFF('SECOND', ppg_prop.TIMESTAMP_VAL, spine.TIMESTAMP_SEC)
        ELSE NULL
    END AS PPG_AGE_SECONDS

FROM time_spine AS spine

-- Exact match joins
LEFT JOIN ECG_DATA_FLATTENED AS ecg_exact
    ON spine.PATIENT_ID = ecg_exact.PATIENT_ID
    AND spine.TIMESTAMP_SEC = ecg_exact.TIMESTAMP_VAL

LEFT JOIN EDA_DATA_FLATTENED AS eda_exact
    ON spine.PATIENT_ID = eda_exact.PATIENT_ID
    AND spine.TIMESTAMP_SEC = eda_exact.TIMESTAMP_VAL

LEFT JOIN PPG_DATA_FLATTENED AS ppg_exact
    ON spine.PATIENT_ID = ppg_exact.PATIENT_ID
    AND spine.TIMESTAMP_SEC = ppg_exact.TIMESTAMP_VAL

-- ASOF joins for forward-fill propagation
ASOF JOIN ECG_DATA_FLATTENED AS ecg_prop
    MATCH_CONDITION(spine.TIMESTAMP_SEC >= ecg_prop.TIMESTAMP_VAL)
    ON spine.PATIENT_ID = ecg_prop.PATIENT_ID

ASOF JOIN EDA_DATA_FLATTENED AS eda_prop
    MATCH_CONDITION(spine.TIMESTAMP_SEC >= eda_prop.TIMESTAMP_VAL)
    ON spine.PATIENT_ID = eda_prop.PATIENT_ID

ASOF JOIN PPG_DATA_FLATTENED AS ppg_prop
    MATCH_CONDITION(spine.TIMESTAMP_SEC >= ppg_prop.TIMESTAMP_VAL)
    ON spine.PATIENT_ID = ppg_prop.PATIENT_ID

ORDER BY spine.PATIENT_ID, spine.TIMESTAMP_SEC;

